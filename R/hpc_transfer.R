# HPC file transfer utilities for RHESSys

#' Extract climate input files from a basestation file
#'
#' Reads a RHESSys basestation file and returns paths to all existing climate input files.
#' @param base_station_file Path to the basestation file
#' @return Character vector of paths to existing climate input files
#' @keywords internal
.get_clim_files_from_basestation <- function(base_station_file) {
  if (!file.exists(base_station_file)) {
    warning("Base station file not found: ", base_station_file)
    return(character())
  }
  
  tmp <- read.table(base_station_file)
  clim_base <- tmp$V1[tmp$V2 == "climate_prefix"]
  
  if (length(clim_base) == 0) {
    warning("No climate_prefix found in basestation file: ", base_station_file)
    return(character())
  }
  
  opts <- c(".rain", ".tmin", ".tmax", ".tavg", ".dayl", ".daytime_rain_duration",
            ".LAI_scalar", ".Ldown", ".Kdown_direct", ".Kdown_diffuse", ".ndep_NO3", ".ndep_NH4",
            ".PAR_direct", ".PAR_diffuse", ".relative_humidity", ".tday", ".tnightmax", ".tsoil",
            ".vpd", ".wind", ".CO2", ".lapse_rate_tmin", ".lapse_rate_tmax", ".tdewpoint")
  
  clim_files <- paste0(clim_base, opts)
  clim_files[file.exists(clim_files)]
}

#' Build a comprehensive RHESSys input file list
#'
#' Creates a standardized list of all files needed for a RHESSys run, prioritizing
#' generated file lists from run_rhessys_single/multi over manual file discovery.
#'
#' @param generated_files List of files generated by run_rhessys_single (with elements:
#'   def_files, hdr_files, tec_files, output_filters, clim_bases)
#' @param input_rhessys RHESSys inputs list (contains world_file, flow_file, base_stations path)
#' @param input_hdr Header list of definition files (used as fallback if def_files not in generated_files)
#' @param input_tec_data Tec events data frame (used to find associated redefine files)
#'
#' @return A standardized list with elements:
#'   - world_file: Path to worldfile
#'   - flow_file: Path to flow table
#'   - base_station_file: Path to basestation file
#'   - climate_files: Vector of climate input file paths
#'   - hdr_files: Vector of header file paths
#'   - def_files: Vector of definition file paths
#'   - tec_files: Vector of tec event file paths
#'   - output_filters: Vector of output filter file paths
#'   - redef_files: Vector of worldfile redefine files (if any)
#'   - all_files: Flattened vector of all files for transfer
#'
#' @export
build_rh_input_file_list <- function(
  generated_files = NULL,
  input_rhessys,
  input_hdr = NULL,
  input_tec_data = NULL
) {
  filelist <- list()
  
  # -------- Static base files (always required) --------
  filelist$world_file <- input_rhessys$world_file
  filelist$flow_file <- input_rhessys$flow_file
  
  if (!file.exists(filelist$world_file)) {
    stop("World file does not exist: ", filelist$world_file)
  }
  if (!file.exists(filelist$flow_file)) {
    stop("Flow file does not exist: ", filelist$flow_file)
  }
  
  # -------- Climate files --------
  # Priority: from generated_files > derive from basestation > from input_hdr
  if (!is.null(generated_files) && !is.null(generated_files$clim_bases)) {
    filelist$base_station_file <- generated_files$clim_bases
    filelist$climate_files <- .get_clim_files_from_basestation(generated_files$clim_bases)
  } else if (!is.null(input_hdr) && !is.null(input_hdr$base_stations)) {
    filelist$base_station_file <- input_hdr$base_stations
    filelist$climate_files <- .get_clim_files_from_basestation(input_hdr$base_stations)
  } else {
    warning("No base station file specified; climate files will not be included in transfer")
    filelist$base_station_file <- NA
    filelist$climate_files <- character()
  }

  # -------- Unmodified def files --------
  filelist$def_files = c(
    input_hdr$basin_def,
    input_hdr$hillslope_def,
    input_hdr$zone_def,
    input_hdr$soil_def,
    input_hdr$landuse_def,
    input_hdr$stratum_def
  )
  
  # -------- Generated/modified files (from run_rhessys_single output) --------
  if (!is.null(generated_files)) {
    filelist$hdr_files <- generated_files$hdr_files %||% character()
    filelist$def_files <- c(filelist$def_files, generated_files$def_files)
    filelist$tec_files <- generated_files$tec_files %||% character()
    filelist$output_filters <- generated_files$output_filters %||% character()
  }
  
  # -------- Redefine files (from tec events) --------
  filelist$redef_files <- character()
  if (!is.null(input_tec_data) && is.data.frame(input_tec_data) && any(grepl("redefine", input_tec_data$name))) {
    tec_redef <- input_tec_data[grepl("redefine", input_tec_data$name), ]
    redefs <- paste0(
      input_rhessys$world_file, ".Y", tec_redef$year, "M", tec_redef$month,
      "D", tec_redef$day, "H", tec_redef$hour
    )
    filelist$redef_files <- redefs[file.exists(redefs)]
  }
  # -------- Fire Grids --------
  if ("fire_grid_prefix" %in% names(input_hdr)) {
      filelist$fire_grids = paste(unname(unlist(input_hdr$fire_grid_prefix)), c(".dem", ".hillslope", ".patch",".zone"), sep = "")
  } else {
      filelist$fire_grids = character()
  }
  
  # -------- Aggregate all files for transfer --------
  filelist$all_files <- unique(c(
    filelist$world_file,
    filelist$flow_file,
    filelist$base_station_file,
    filelist$climate_files,
    filelist$hdr_files,
    filelist$def_files,
    filelist$tec_files,
    filelist$output_filters,
    filelist$redef_files,
    filelist$fire_grids
  ))
  
  # Remove NA values and non-existent files
  filelist$all_files <- filelist$all_files[!is.na(filelist$all_files)]
  filelist$all_files <- filelist$all_files[file.exists(filelist$all_files)]
  
  # Validate
  if (length(filelist$all_files) == 0) {
    warning("No input files found. Check your file paths and generated_files list.")
  }
  
  return(filelist)
}

# Helper: %||% operator for NULL coalescing
`%||%` <- function(x, y) {
  if (is.null(x)) y else x
}

#' Format RHESSys run commands for HPC submission
#'
#' @param rhout Character vector of RHESSys commands
#' @param name Label to include in the output filename
#' @param rh_bin_replace Optional replacement RHESSys binary path
#' @param prefix_cmd Optional command prefix
#' @export
rhout_write_for_hpc <- function(rhout, name, rh_bin_replace = NULL, prefix_cmd = NULL) {
  # Standardize input format
  rhout_str <- unlist(rhout)
  
  # Clean up WSL wrapper artifacts
  rhout_str <- gsub("^wsl bash -lc ", "", rhout_str)
  rhout_str <- gsub("^wsl ", "", rhout_str)
  rhout_str <- gsub('\\"', "", rhout_str)
  
  # Replace RHESSys binary path if requested
  if (!is.null(rh_bin_replace)) {
    rhout_str <- gsub(
      "^.*rhessys\\S+\\s+",
      paste0(trimws(rh_bin_replace), " "),
      rhout_str
    )
  }
  
  # Ensure -par option is at end (RHESSys requirement)
  if (any(!grepl("-par \\d+", rhout_str))) {
    rhout_str <- gsub(" -par \\d+", "", rhout_str)
    rhout_str <- paste0(rhout_str, " -par ", seq_along(rhout_str))
  } else {
    x_value <- gsub("-par\\s", "", regmatches(rhout_str, regexpr("-par\\s\\d+", rhout_str)))
    rhout_str <- gsub("-par\\s\\d+ ", "", rhout_str)
    rhout_str <- paste0(rhout_str, " -par ", x_value)
  }
  
  # Add prefix command if provided
  if (!is.null(prefix_cmd)) {
    rhout_str <- paste0("bash -c '", trimws(prefix_cmd), " && ", rhout_str, "'")
  }
  
  # Write to output file
  outfile <- paste0(
    "scripts/", name, "_runcmds_",
    format(Sys.time(), "%Y-%m-%d--%H-%M-%S"), ".txt"
  )
  writeLines(text = rhout_str, con = outfile)
  cat("Wrote RHESSys commands to:", outfile, "\n")
  
  return(outfile)
}

#' Transfer RHESSys inputs and commands to HPC via rsync or scp
#'
#' Transfers all necessary RHESSys input files to a remote HPC system and optionally
#' submits the run commands. Prioritizes rsync for efficiency; falls back to scp if needed.
#'
#' @param rh_commands Character vector of formatted RHESSys command strings (from run_rhessys_single/multi)
#' @param rh_file_list List of input files to transfer (from build_rh_input_file_list or
#'   generated_files output of run_rhessys_single)
#' @param name Label for this transfer batch (used in naming output files)
#' @param remote_user Remote user in format "user@hostname" (e.g., "wburke@pronghorn.rc.unr.edu")
#' @param remote_dest Remote destination path (e.g., "/data/gpfs/assoc/firelab/william.burke/Ward/")
#' @param rhessys_binary_remote Path to RHESSys binary on remote system (default: "/RHESSys/rhessys7.5")
#' @param prefix_cmd Optional command to execute before RHESSys (e.g., loading modules)
#' @param transfer_method File transfer method: "rsync" (default, faster) or "scp" (backup)
#' @param ssh_key Path to SSH private key (default: "~/rsa_key")
#' @param submit_job Logical; if TRUE, submits the run script to HPC job scheduler
#'   after file transfer (requires run script at remote location)
#' @param job_script Remote path to job submission script (e.g., "./scripts/run_dyn_omp.sh")
#'
#' @return Character vector containing path(s) to remote run command file(s)
#'
#' @details
#' This function:
#' 1. Validates input files exist locally
#' 2. Formats RHESSys commands for HPC (properly ordering -par flags)
#' 3. Creates remote directory structure
#' 4. Transfers files via rsync (preferred) or scp
#' 5. Optionally submits jobs to remote scheduler
#'
#' Assumes WSL is available for SSH/rsync commands on Windows.
#'
#' @export
transfer_to_hpc <- function(
  rh_commands,
  rh_file_list,
  name,
  remote_user,
  remote_dest,
  rhessys_binary_remote = "/RHESSys/rhessys7.5",
  prefix_cmd = NULL,
  transfer_method = "rsync",
  ssh_key = "~/rsa_key",
  submit_job = FALSE,
  job_script = NULL
) {
  # -------- Input validation --------
  transfer_method <- tolower(transfer_method)
  if (!transfer_method %in% c("rsync", "scp")) {
    stop("transfer_method must be 'rsync' or 'scp'")
  }
  
  if (!grepl("@", remote_user)) {
    stop("remote_user must be in format 'user@hostname'")
  }
  
  if (!endsWith(remote_dest, "/")) {
    remote_dest <- paste0(remote_dest, "/")
  }
  
  # -------- Prepare commands --------
  cmd_file <- rhout_write_for_hpc(
    rh_commands,
    name,
    rh_bin_replace = rhessys_binary_remote,
    prefix_cmd = prefix_cmd
  )
  
  # -------- Standardize file list structure --------
  if (!is.list(rh_file_list) || is.null(names(rh_file_list))) {
    stop("rh_file_list must be a named list with elements: all_files (at minimum)")
  }
  
  files_to_transfer <- if (!is.null(rh_file_list$all_files)) {
    rh_file_list$all_files
  } else {
    unique(unlist(rh_file_list))
  }
  
  files_to_transfer <- c(files_to_transfer, cmd_file)
  files_to_transfer <- files_to_transfer[file.exists(files_to_transfer)]
  
  if (length(files_to_transfer) == 0) {
    stop("No files found to transfer. Check file paths.")
  }
  
  cat("\n--- File Transfer Summary ---\n")
  cat("Total files to transfer:", length(files_to_transfer), "\n")
  cat("Method:", transfer_method, "\n\n")
  
  # -------- Create remote directories --------
  remote_dirs <- unique(dirname(files_to_transfer))
  remote_dirs_str <- paste(remote_dirs, collapse = " ")
  
  dircmd <- sprintf(
    "wsl ssh -i %s %s \"cd %s && mkdir -p %s\"",
    ssh_key, remote_user, remote_dest, remote_dirs_str
  )
  
  cat("Creating remote directories...\n")
  dir_status <- system(dircmd)
  if (!identical(dir_status, 0L)) {
    stop("Failed to create remote directories")
  }
  
  # -------- Transfer files --------
  if (transfer_method == "rsync") {
    cat("Transferring files via rsync...\n")
    
    # Use temp file for file list (avoids command line length issues on Windows)
    files_tmp <- tempfile(fileext = ".txt")
    writeLines(files_to_transfer, files_tmp)
    
    # Convert Windows path to WSL path
    files_wsl <- system(
      sprintf("wsl wslpath -u \"%s\"", files_tmp),
      intern = TRUE
    )
    
    rsync_cmd <- sprintf(
      "wsl rsync -aRv --files-from=%s . -e \"ssh -i %s\" %s:%s",
      files_wsl, ssh_key, remote_user, remote_dest
    )
    
    rsync_status <- system(rsync_cmd)
    if (!identical(rsync_status, 0L)) {
      stop("rsync transfer failed with status ", rsync_status)
    }
    
    cat("rsync transfer completed successfully.\n")
    
  } else if (transfer_method == "scp") {
    cat("Transferring files via scp...\n")
    
    # Group files by directory for efficiency
    file_groups <- split(files_to_transfer, dirname(files_to_transfer))
    
    for (src_dir in names(file_groups)) {
      src_files <- file_groups[[src_dir]]
      remote_dir <- paste0(remote_user, ":", remote_dest, src_dir)
      
      scp_cmd <- sprintf(
        "scp -i %s -p %s %s",
        ssh_key,
        paste(src_files, collapse = " "),
        remote_dir
      )
      
      scp_status <- system(scp_cmd)
      if (!identical(scp_status, 0L)) {
        warning("scp transfer failed for ", src_dir, " (status: ", scp_status, ")")
      }
    }
    
    cat("scp transfer completed.\n")
  }
  
  # -------- Optional job submission --------
  if (submit_job) {
    if (is.null(job_script)) {
      warning("submit_job = TRUE but job_script not specified. Skipping submission.")
    } else {
      cat("\nSubmitting jobs to remote scheduler...\n")
      
      submit_cmd <- sprintf(
        "wsl ssh -i %s %s \"cd %s && %s %s\"",
        ssh_key, remote_user, remote_dest, job_script, cmd_file
      )
      
      submit_status <- system(submit_cmd)
      if (!identical(submit_status, 0L)) {
        warning("Job submission failed with status ", submit_status)
      } else {
        cat("Job submission successful.\n")
      }
    }
  }
  
  return(cmd_file)
}

#' Test SSH connectivity to HPC system via WSL
#'
#' @param user Remote user@host string
#' @param key Path to SSH private key
#' @param timeout Connection timeout in seconds
#' @param remote_cmd Command to execute for the test
#'
#' @return List with elements:
#'   - ok: Logical indicating successful connection
#'   - status: Numeric exit status
#'   - output: Character vector of command output
#'
#' @export
test_hpc_ssh <- function(
  user = "wburke@pronghorn.rc.unr.edu",
  key = "~/rsa_key",
  timeout = 10,
  remote_cmd = "echo 'SSH connection successful'"
) {
  cmd <- "wsl"
  args <- c(
    "ssh",
    "-i", key,
    "-o", "BatchMode=yes",
    "-o", "StrictHostKeyChecking=accept-new",
    "-o", sprintf("ConnectTimeout=%d", timeout),
    user,
    remote_cmd
  )
  
  out <- tryCatch(
    system2(cmd, args, stdout = TRUE, stderr = TRUE),
    error = function(e) structure(character(), status = 1L, class = "try-error")
  )
  
  status <- attr(out, "status")
  if (is.null(status)) status <- 0L
  
  list(
    ok = identical(status, 0L),
    status = status,
    output = out
  )
}
